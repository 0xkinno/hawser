if (want("cross_edit")) {
  const r = await run("b3");
  await startCall(r.c);
  await r.c.bots.observer.waitTag("rev:log-charterer", 30_000);
  const ids = await docIds(r.c);
  const before = await r.c.bots.desk.api.op<Array<{ content: string }>>("load_internal_documents", {
    ids: [ids["log-charterer"] as string],
  });
  let outcome: unknown;
  try {
    await r.c.bots.mate.api.op("update_room_document", {
      document_id: ids["log-charterer"],
      content: logDoc("charterer", CALL, VESSEL),
    });
    outcome = { refused: false };
  } catch (e) {
    outcome = { refused: true, status: (e as HttpError).status, body: (e as HttpError).body };
  }
  await sleep(3000);
  const after = await r.c.bots.desk.api.op<Array<{ content: string }>>("load_internal_documents", {
    ids: [ids["log-charterer"] as string],
  });
  await writeResult(r.w, {
    id: "b3",
    question: "ship-mate edits log-charterer",
    status: "observed",
    summary: `Switch refused: ${JSON.stringify(outcome)}. Content unchanged: ${before[0]?.content === after[0]?.content}. Revision cards for log-charterer: ${count(r.c, "rev:log-charterer")} (no change seen by the Timekeeper).`,
    observed: {
      outcome,
      contentUnchanged: before[0]?.content === after[0]?.content,
      charterRevisionCards: count(r.c, "rev:log-charterer"),
    },
  });
  r.stop();
}

