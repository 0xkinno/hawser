const only = process.env.HAWSER_FAULT;
const want = (n: string) => !only || only === n;

interface Run {
  w: World;
  c: Cast;
  a: TkProc;
  b?: TkProc;
  stop: () => void;
}

async function run(label: string, opts: { standby?: boolean; poll?: number } = {}): Promise<Run> {
  const w = await freshRoom(loadWorld(), label);
  const c = await cast(w);
  const dir = freshDir(`.data/campaign/${label}-${Date.now()}`);
  const env = { HAWSER_POLL_MS: String(opts.poll ?? 20_000) };
  const a = spawnTimekeeper(w, "a", `${dir}/a`, env);
  await a.waitLine(/holds the timekeeper role/, 30_000);
  let b: TkProc | undefined;
  if (opts.standby) {
    b = spawnTimekeeper(w, "b", `${dir}/b`, env);
    await b.waitLine(/connected, protocol/, 20_000);
  }
  const r: Run = {
    w,
    c,
    a,
    ...(b ? { b } : {}),
    stop: () => {
      c.closeAll();
      a.kill();
      b?.kill();
    },
  };
  return r;
}

const count = (c: Cast, prefix: string) => c.bots.observer.tags().filter((t) => t.startsWith(prefix)).length;
async function until(f: () => boolean, ms: number, what: string) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    if (f()) return;
    await sleep(100);
  }
  throw new Error(`timed out waiting for ${what}`);
}

