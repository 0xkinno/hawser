if (want("rewrite_after_sign")) {
  const secs: number[] = [];
  const trials: unknown[] = [];
  for (let i = 1; i <= 5; i++) {
    const r = await run(`b4-${i}`, { poll: 20_000 });
    await startCall(r.c);
    const d1 = await signAll(r.c, 1);
    const ids = await docIds(r.c);
    const rewritten = VESSEL.map((l) => (l.kind === "ALL_FAST" ? { ...l, time: "2026-11-16 12:00" } : l));
    const t0 = Date.now();
    await r.c.bots.clerk.api.op("update_room_document", {
      document_id: ids["log-agency"],
      content: logDoc("agency", CALL, rewritten),
    });
    await r.c.bots.observer.waitMessage(
      (m) => m.body.includes("NON-APPEND CHANGE"),
      40_000,
      "the NON-APPEND card",
    );
    const detect = (Date.now() - t0) / 1000;
    await r.c.bots.observer.waitTag("void:", 20_000);
    const voidCard = r.c.bots.observer.messages().find((m) => m.body.includes("[hk:void:"));
    await r.c.bots.observer.waitTag("sof:v2:", 20_000);
    const d2 = (r.c.bots.observer.lastTag("sof:v2:") as string).split(":")[2];
    await r.c.bots.agent.say(`@timekeeper sign ${d1}`);
    await until(
      () => r.c.bots.observer.messages().some((m) => m.body.includes(`${d1} is not the current version`)),
      15_000,
      "refusal of the old digest",
    );
    secs.push(detect);
    trials.push({
      trial: i,
      detectSeconds: detect,
      oldDigest: d1,
      newDigest: d2,
      voidCard: voidCard?.body.split("\n")[0],
      oldDigestRefused: true,
      pollMs: 20000,
    });
    r.stop();
    await sleep(8000);
  }
  await writeResult(loadWorldSync(), {
    id: "b4",
    question: "agency-clerk rewrites its own log after all three signed",
    status: "observed",
    summary: `Rewrite detected, signatures voided, room told, new version issued in all 5 trials. Detection median ${median(secs).toFixed(1)} s (min ${Math.min(...secs).toFixed(1)}, max ${Math.max(...secs).toFixed(1)}) with the default 20 s poll, because Switch posts an "updated room document" notice that triggers an immediate re-read.`,
    observed: { trials, medianDetectSeconds: median(secs) },
    caveats: ["Simulated people on a local switch-core."],
  });
}

function loadWorldSync(): World {
  return JSON.parse(readFileSync(".data/world.json", "utf8")) as World;
}

// ---------------------------------------------------------------------------------------------- B6 x5
if (want("kill_lease")) {
  const secs: number[] = [];
  const trials: unknown[] = [];
  for (let i = 1; i <= 5; i++) {
    const r = await run(`b6-${i}`, { standby: true, poll: 1000 });
    await startCall(r.c);
    const d = await signAll(r.c, 1);
    const tagsBefore = new Set(r.c.bots.observer.tags());
    const bLines = r.b?.lines.length ?? 0;
    const t0 = Date.now();
    r.a.kill("SIGKILL");
    const line = await (r.b as TkProc).waitLine(/holds the timekeeper role/, 60_000);
    const dt = (Date.now() - t0) / 1000;
    const rebuilt = await (r.b as TkProc).waitLine(/rebuilt from the room/, 20_000);
    await sleep(3000);
    const digestAfter = /digest (\S+)/.exec(rebuilt)?.[1];
    const dup = r.c.bots.observer.tags().filter((t, ix, arr) => arr.indexOf(t) !== ix);
    // the new holder must still act: a refusal for an unenrolled sender
    await r.c.bots.mate.say(`@timekeeper sign ${d}`);
    await until(
      () => r.c.bots.observer.messages().filter((m) => m.name === "timekeeper-b").length > 0,
      20_000,
      "a card from timekeeper-b",
    );
    secs.push(dt);
    trials.push({
      trial: i,
      failoverSeconds: dt,
      digestBefore: d,
      digestAfterTakeover: digestAfter,
      digestIdentical: d === digestAfter,
      duplicateTags: dup,
      newCardsBySecondHolder: r.c.bots.observer.tags().filter((t) => !tagsBefore.has(t)),
      holdLine: line.slice(0, 120),
      bLinesBefore: bLines,
    });
    r.stop();
    await sleep(8000);
  }
  const allSame = trials.every((t) => (t as { digestIdentical: boolean }).digestIdentical);
  await writeResult(loadWorldSync(), {
    id: "b6",
    question: "Kill timekeeper-a",
    status: "observed",
    summary: `timekeeper-b took the role after a median ${median(secs).toFixed(1)} s (min ${Math.min(...secs).toFixed(1)}, max ${Math.max(...secs).toFixed(1)}) over 5 SIGKILL trials; digest identical after takeover in ${trials.filter((t) => (t as { digestIdentical: boolean }).digestIdentical).length} of 5; duplicate cards: ${trials.reduce<number>((n, t) => n + (t as { duplicateTags: string[] }).duplicateTags.length, 0)}. The server keeps a dead holder's connection, and so its role lease, until 30 s of silence (HEARTBEAT_TTL_SECONDS).`,
    observed: { trials, medianSeconds: median(secs), allDigestsIdentical: allSame },
  });
}

