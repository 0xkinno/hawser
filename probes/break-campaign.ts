if (want("restart")) {
  const r = await run("b7", { poll: 2000 });
  await startCall(r.c);
  await r.c.bots.observer.waitTag("sof:v1:", 30_000);
  const before = r.c.bots.observer.tags().length;
  const digest = (r.c.bots.observer.lastTag("sof:v1:") as string).split(":")[2];
  r.c.closeAll();
  restartSwitch();
  const c2 = await cast(r.w);
  await sleep(2000);
  await c2.bots.priya.say("noted");
  await until(
    () => c2.bots.observer.tags().filter((t) => t.startsWith("rna:")).length >= 1,
    60_000,
    "a card after the restart",
  );
  await sleep(2500);
  const tags = (await c2.bots.observer.api.history(c2.room, 300)).flatMap((h) =>
    [...h.body.matchAll(/\[hk:([^\]]+)\]/g)].map((x) => x[1] as string),
  );
  const dups = tags.filter((t, i, a) => a.indexOf(t) !== i);
  const lines = r.a.lines
    .filter((l) => /connection closed|connected,|gap|holds|rebuilt/.test(l))
    .map((l) => l.slice(0, 160));
  await writeResult(r.w, {
    id: "b7",
    question: "Restart switch-core mid-call",
    status: "observed",
    summary: `Timekeeper reconnected and kept working: a message sent after the restart got its card; duplicate tags in the room history: ${dups.length}; version 1 digest ${digest} unchanged. Timekeeper log lines: ${lines.length}.`,
    observed: { tagsBefore: before, duplicateTagsAfter: dups, timekeeperLog: lines },
  });
  c2.closeAll();
  r.a.kill();
}

